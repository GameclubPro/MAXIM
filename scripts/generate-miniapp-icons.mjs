import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import * as icons from 'iconoir-react';
import { chromium } from 'playwright';
import {
  APP_ICON_NAMES,
  APP_LAZY_ICON_NAMES,
} from '../apps/miniapp/src/components/ui/app-icon-names.ts';

// Preserve the library artwork without shipping a React component per shared icon.
const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const license = await readFile(
    new URL('../node_modules/iconoir-react/LICENSE', import.meta.url),
    'utf8',
  );
  const groups = [
    { names: APP_ICON_NAMES, file: 'iconoir-ui.svg' },
    { names: APP_LAZY_ICON_NAMES, file: 'iconoir-route.svg' },
  ];
  for (const { names, file } of groups) {
    const symbols = await page.evaluate(
      (entries) => {
        const ns = 'http://www.w3.org/2000/svg';
        return entries.map(([name, markup]) => {
          const svg = new DOMParser().parseFromString(markup, 'image/svg+xml').documentElement;
          if (svg.localName !== 'svg') throw new Error(`Invalid library icon: ${name}`);
          const symbol = document.createElementNS(ns, 'symbol');
          symbol.id = name;
          symbol.setAttribute('viewBox', svg.getAttribute('viewBox'));
          symbol.append(...svg.childNodes);
          return new XMLSerializer().serializeToString(symbol);
        });
      },
      names.map((name) => [name, renderToStaticMarkup(createElement(icons[name]))]),
    );
    const output = `<!-- Generated by scripts/generate-miniapp-icons.mjs from Iconoir.\n${license.trim()}\n-->\n<svg xmlns="http://www.w3.org/2000/svg">\n${symbols.join('\n')}\n</svg>\n`;
    const destination = new URL(`../apps/miniapp/src/assets/${file}`, import.meta.url);
    if (process.argv.includes('--check')) {
      assert.equal(await readFile(destination, 'utf8'), output, `Regenerate ${file}.`);
    } else {
      await writeFile(destination, output);
    }
    console.log(
      `${file}: ${names.length} icons${process.argv.includes('--check') ? ' verified' : ' generated'}.`,
    );
  }
} finally {
  await browser.close();
}

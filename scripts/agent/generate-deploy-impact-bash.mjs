#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

import { normalizeRepoPath, validateImpactConfig } from './impact-config.mjs';

const root = resolve(import.meta.dirname, '../..');
const configPath = resolve(root, 'config/change-impact.json');
const outputPath = resolve(root, 'infra/scripts/lib/change-impact-components.generated.sh');
const componentVariables = Object.freeze({
  'api-shared': 'MAXIM_IMPACT_PATH_API_SHARED',
  'miniapp-major-static': 'MAXIM_IMPACT_PATH_MINIAPP_MAJOR_STATIC',
  'admin-static': 'MAXIM_IMPACT_PATH_ADMIN_STATIC',
});

export function globToBashEre(pattern) {
  const normalized = normalizeRepoPath(pattern);
  let source = '';

  for (let index = 0; index < normalized.length; index += 1) {
    const character = normalized[index];
    if (character === '*') {
      if (normalized[index + 1] === '*') {
        index += 1;
        if (normalized[index + 1] === '/') {
          index += 1;
          source += '(.*/)?';
        } else {
          source += '.*';
        }
      } else {
        source += '[^/]*';
      }
      continue;
    }
    if (character === '?') {
      source += '[^/]';
      continue;
    }
    source += escapeBashEre(character);
  }

  return `^${source}$`;
}

export function renderDeployImpactBash(rawConfig) {
  const config = validateImpactConfig(JSON.parse(rawConfig), 'config/change-impact.json');
  const digest = createHash('sha256').update(rawConfig).digest('hex');
  const lines = [
    '#!/usr/bin/env bash',
    '# Generated by scripts/agent/generate-deploy-impact-bash.mjs. Do not edit by hand.',
    `# Source: config/change-impact.json sha256=${digest}`,
    '',
  ];

  config.rules.forEach((rule, index) => {
    lines.push(
      `readonly MAXIM_IMPACT_RULE_${index}_INCLUDE_REGEX=${shellQuote(combineGlobs(rule.include))}`,
    );
    if (rule.exclude.length > 0) {
      lines.push(
        `readonly MAXIM_IMPACT_RULE_${index}_EXCLUDE_REGEX=${shellQuote(combineGlobs(rule.exclude))}`,
      );
    }
  });

  lines.push(
    '',
    'maxim_impact_classify_path() {',
    '  local path="${1:-}"',
    '  path="${path#./}"',
    '  while [[ "$path" == /* ]]; do path="${path#/}"; done',
    '  while [[ -n "$path" && "$path" == */ ]]; do path="${path%/}"; done',
    '',
    '  MAXIM_IMPACT_PATH_CLASSIFIED=0',
    '  MAXIM_IMPACT_PATH_UNKNOWN=0',
    '  MAXIM_IMPACT_PATH_API_SHARED=0',
    '  MAXIM_IMPACT_PATH_MINIAPP_MAJOR_STATIC=0',
    '  MAXIM_IMPACT_PATH_ADMIN_STATIC=0',
    '',
  );

  config.rules.forEach((rule, index) => {
    const include = `$MAXIM_IMPACT_RULE_${index}_INCLUDE_REGEX`;
    const condition =
      rule.exclude.length > 0
        ? `[[ "$path" =~ ${include} ]] && ! [[ "$path" =~ $MAXIM_IMPACT_RULE_${index}_EXCLUDE_REGEX ]]`
        : `[[ "$path" =~ ${include} ]]`;
    lines.push(`  if ${condition}; then`, '    MAXIM_IMPACT_PATH_CLASSIFIED=1');
    for (const component of rule.deployComponents) {
      const variable = componentVariables[component];
      if (!variable) {
        throw new Error(`No generated Bash variable for deploy component ${component}.`);
      }
      lines.push(`    ${variable}=1`);
    }
    lines.push('  fi');
  });

  lines.push(
    '',
    '  if [[ "$MAXIM_IMPACT_PATH_CLASSIFIED" -eq 0 ]]; then',
    '    MAXIM_IMPACT_PATH_UNKNOWN=1',
    '    MAXIM_IMPACT_PATH_API_SHARED=1',
    '    MAXIM_IMPACT_PATH_MINIAPP_MAJOR_STATIC=1',
    '    MAXIM_IMPACT_PATH_ADMIN_STATIC=1',
    '  fi',
    '}',
  );

  return `${lines.join('\n')}\n`;
}

function combineGlobs(patterns) {
  const sources = patterns.map((pattern) => globToBashEre(pattern).slice(1, -1));
  return `^(${sources.map((source) => `(${source})`).join('|')})$`;
}

function escapeBashEre(character) {
  return /[.\\^$+(){}|[\]]/u.test(character) ? `\\${character}` : character;
}

function shellQuote(value) {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

function runCli(argv) {
  const unknown = argv.filter((argument) => argument !== '--check');
  if (unknown.length > 0) {
    throw new Error(`Unknown argument: ${unknown[0]}`);
  }
  const expected = renderDeployImpactBash(readFileSync(configPath, 'utf8'));
  if (argv.includes('--check')) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
    if (current !== expected) {
      throw new Error(
        'Generated deploy impact mapping is stale. Run: node scripts/agent/generate-deploy-impact-bash.mjs',
      );
    }
    return;
  }
  writeFileSync(outputPath, expected, { mode: 0o755 });
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  try {
    runCli(process.argv.slice(2));
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 2;
  }
}

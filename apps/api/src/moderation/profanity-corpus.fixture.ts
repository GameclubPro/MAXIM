function renderTemplate(template: string, term: string, detail?: string): string {
  return template.replace('{term}', term).replace('{detail}', detail ?? '');
}

function buildGeneratedAllowCases(): string[] {
  const cases = new Set<string>();

  SAFE_REAL_WORLD_TERMS.forEach((term, termIndex) => {
    SAFE_REAL_WORLD_TEMPLATES.forEach((template, templateIndex) => {
      for (let offset = 0; offset < 4; offset += 1) {
        const detail =
          SAFE_REAL_WORLD_DETAILS[
            (termIndex * 7 + templateIndex * 3 + offset) % SAFE_REAL_WORLD_DETAILS.length
          ]!;
        cases.add(renderTemplate(template, term, detail));
      }
    });
  });

  return [...cases];
}

function buildGeneratedBlockCases(): string[] {
  const cases = new Set<string>();

  BLOCK_REAL_WORLD_TERMS.forEach((term) => {
    BLOCK_REAL_WORLD_TEMPLATES.forEach((template) => {
      cases.add(renderTemplate(template, term));
    });
  });

  cases.add('б л я т ь, хватит уже');
  cases.add('х у й тебе, а не доступ');
  cases.add('п и з д а чату');
  cases.add('ну ты 6лять опять начал');
  cases.add('mne pohuy na vas');
  cases.add('zaebal uzhe spamit');

  return [...cases];
}


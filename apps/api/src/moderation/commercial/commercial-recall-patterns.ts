import type { CommercialCampaignContext } from '../commercial-campaign.util';

export type CommercialRecallCap = 'WARN' | 'REVIEW_ONLY';

export type CommercialRecallMatch = {
  label: string;
  cap: CommercialRecallCap;
};

const PRICE_PATTERN =
  /(?:^|[^\p{L}\p{N}_-])(?:\d[\d\s.,]{0,8}\s*(?:₽|руб(?:\.|л[\p{L}\p{N}_-]*)?|р\.?|т\.?\s*р\.?)|цен[аы]?\s*[:=-]?\s*\d[\d\s.,]{0,8}|от\s+\d{2,}(?!\s*(?:лет|год[а-яё-]*|месяц[а-яё-]*|недел[а-яё-]*|дн[а-яё-]*|шт)(?=$|[^\p{L}\p{N}_-])))(?=$|[^\p{L}\p{N}_-])/giu;
const PHONE_OR_LINK_PATTERN =
  /(?:\[phone\]|\[url\]|(?:\+?7|8)(?:[\s().‐‑‒–—―•·|/:+-]*\d){10}|https?:\/\/)/iu;

function countMatches(value: string, pattern: RegExp, limit: number): number {
  const matcher = new RegExp(
    pattern.source,
    pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`,
  );
  let count = 0;
  while (matcher.exec(value) && count < limit) {
    count += 1;
  }
  return count;
}

function countDistinctPatternMatches(value: string, patterns: readonly RegExp[]): number {
  return patterns.reduce((count, pattern) => count + (pattern.test(value) ? 1 : 0), 0);
}

function sliceAfterLastRelevantMatch(
  value: string,
  pattern: RegExp,
  requiredPattern: RegExp,
): string {
  pattern.lastIndex = 0;
  const matchIndexes: number[] = [];
  for (const match of value.matchAll(pattern)) {
    matchIndexes.push(match.index);
  }
  pattern.lastIndex = 0;
  for (let index = matchIndexes.length - 1; index >= 0; index -= 1) {
    const candidate = value.slice(matchIndexes[index]);
    requiredPattern.lastIndex = 0;
    if (requiredPattern.test(candidate)) {
      requiredPattern.lastIndex = 0;
      return candidate;
    }
  }
  requiredPattern.lastIndex = 0;
  return value;
}

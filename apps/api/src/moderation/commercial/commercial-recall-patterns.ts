export function resolveRecurringBuyoutRecall(params: {
  text: string;
  campaignContext?: CommercialCampaignContext | null;
}): CommercialRecallMatch | null {
  const { text, campaignContext } = params;
  if (shouldSkipBoundedRecall(text, BUYOUT_RECALL_PREFILTER)) {
    return null;
  }
  if (
    /(?:^|[^\p{L}\p{N}_-])(?:отдам|подарю|утилизаци[а-яё-]*|переработк[а-яё-]*|для\s+коллекци[а-яё-]*|ненужн[а-яё-]*\s+комплектующ[а-яё-]*)(?=$|[^\p{L}\p{N}_-])/iu.test(
      text,
    )
  ) {
    return null;
  }

  if (
    /^(?=[\s\S]{0,900}принима(?:ем|ю)\s+металлолом)(?=[\s\S]{0,900}(?:\d+(?:[.,]\d+)?\s*руб|самовывоз))(?=[\s\S]{0,900}(?:звоните|пишите|\[phone\]|любое\s+время\s+суток))[\s\S]+/iu.test(
      text,
    )
  ) {
    return { label: 'recurring-scrap-buyout', cap: 'WARN' };
  }

  const electronicsCategoryCount = countMatches(
    text,
    /(?:^|[^\p{L}\p{N}_-])(?:измерительн[а-яё-]*\s+прибор[а-яё-]*|частотомер[а-яё-]*|осциллограф[а-яё-]*|генератор[а-яё-]*\s+частот[а-яё-]*|радиостанци[а-яё-]*|эвм|радиолюбительск[а-яё-]*\s+оборудовани[а-яё-]*|раци[а-яё-]*|радиодетал[а-яё-]*|плат[ыа])(?=$|[^\p{L}\p{N}_-])/giu,
    12,
  );
  const hasRepeatedCampaign =
    (campaignContext?.sameTextDistinctChatCount ?? 0) >= 2 ||
    (campaignContext?.nearTextDistinctChatCount ?? 0) >= 2;
  if (
    /(?:^|[^\p{L}\p{N}_-])куплю(?=$|[^\p{L}\p{N}_-])/iu.test(text) &&
    electronicsCategoryCount >= 3 &&
    (PHONE_OR_LINK_PATTERN.test(text) || RESPONSE_PATTERN.test(text) || hasRepeatedCampaign)
  ) {
    return { label: 'professional-electronics-buyout', cap: 'WARN' };
  }

  return null;
}


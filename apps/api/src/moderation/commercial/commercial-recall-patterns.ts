function isPublicOrSafetyLinkContext(text: string): boolean {
  return /(?:^|[^\p{L}\p{N}_-])(?:официальн[а-яё-]*\s+(?:сообщени[а-яё-]*|канал[а-яё-]*)|мчс|экстренн[а-яё-]*|сбор\s+помощ[а-яё-]*|пропал[а-яё-]*\s+человек|итог[а-яё-]*\s+розыгрыш[а-яё-]*|победител[а-яё-]*|приз\s+разыгран)(?=$|[^\p{L}\p{N}_-])/iu.test(
    text,
  );
}

function shouldSkipBoundedRecall(text: string, prefilter: RegExp): boolean {
  return text.length > MAX_BOUNDED_RECALL_TEXT_LENGTH || !prefilter.test(text);
}

function countMatches(value: string, pattern: RegExp, limit: number): number {
  const matcher = new RegExp(
    pattern.source,
    pattern.flags.includes('g') ? pattern.flags : `${pattern.flags}g`,
  );
  let count = 0;
  while (matcher.exec(value) && count < limit) {
    count += 1;
  }
  return count;
}

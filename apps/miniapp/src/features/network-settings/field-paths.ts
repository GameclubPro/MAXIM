export function settingsSectionPaths(
  entityType: 'chat' | 'channel',
  section: NetworkSettingsSection,
): string[] {
  if (entityType === 'channel') {
    if (!Object.hasOwn(CHANNEL_SECTION_FIELDS, section))
      throw new Error('Раздел недоступен для каналов.');
    return [...CHANNEL_SECTION_FIELDS[section as keyof typeof CHANNEL_SECTION_FIELDS]];
  }
  if (Object.hasOwn(SUPPLEMENTARY_CHAT_SECTION_FIELDS, section))
    return [
      ...SUPPLEMENTARY_CHAT_SECTION_FIELDS[
        section as keyof typeof SUPPLEMENTARY_CHAT_SECTION_FIELDS
      ],
    ];
  if (!Object.hasOwn(CHAT_SECTION_FIELDS, section)) throw new Error('Раздел недоступен для чатов.');
  const key = section as ApplySettingsSection;
  if (key === 'stopWords') return STOP_FIELDS.map((path) => 'stopWordsPolicy.' + path);
  return [
    ...CHAT_SECTION_FIELDS[key].filter((path) => !DERIVED.has(path)),
    ...CHAT_SECTION_MEDIA[key].map((path) => 'botSpeechMedia.' + path),
  ];
}
